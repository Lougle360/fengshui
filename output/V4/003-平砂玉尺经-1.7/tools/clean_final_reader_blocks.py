def clean(text, block_id):
    if block_id in FURNITURE:
        return ''
    text = text.strip()
    if block_id in SPECIAL:
        text = text.replace(*SPECIAL[block_id])
    if block_id in EXACT_TEXT:
        text = EXACT_TEXT[block_id]
    for before, after in TEXT_REPLACEMENTS.get(block_id, []):
        text = text.replace(before, after)
    previous = None
    while previous != text:
        previous = text
        text = TAIL.sub('', text).rstrip(' ，；：')
        text = RUNNING_HEAD_TAIL.sub('', text).rstrip(' ，；：')
    text = re.sub(r'。{2,}', '。', text)
    # Keep source uncertainty visible, but remove repetitive production-style
    # wording that interrupts ordinary reading.
    text = re.sub(r'原文此处有“([^\n”]{1,60})”的表述，“[^\n”]{1,30}”具体含义不详', r'〔原文“\1”有疑〕', text)
    text = re.sub(r'原文此处“([^\n”]{1,60})”具体含义不详', r'〔原文“\1”有疑〕', text)
    text = re.sub(r'其中“([^\n”]{1,60})”具体所指不详', r'〔“\1”有疑〕', text)
    text = text.replace('原文此处有缺损，具体含义不详', '〔原文残缺〕')
    text = text.replace('原文此处内容有截断，后续内容缺失', '〔原文残缺〕')
    text = text.replace('具体含义不详', '含义不明').replace('具体所指不详', '所指不明')
    return text

