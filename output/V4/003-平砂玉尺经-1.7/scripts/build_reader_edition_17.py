def occurrences(source_rows: list[dict], aliases: list[str], limit: int = 5) -> list[dict]:
    found = []
    for row in source_rows:
        text = row.get("source_text") or ""
        alias = next((x for x in aliases if x in text), None)
        if alias:
            found.append({
                "block_id": row["block_id"],
                "source_page": row.get("source_page") or page_of(row["block_id"]),
                "quote": excerpt(text, alias),
            })
        if len(found) >= limit:
            break
    return found


