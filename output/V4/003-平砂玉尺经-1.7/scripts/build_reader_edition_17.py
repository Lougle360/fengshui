def build_markdown(rows: list[dict], aids: dict) -> str:
    out = main_reading(aids)
    out += ["# 第二编：原书逐页现代释文（对照查阅编）", "", "本编按物理页保留全部区块，主要用于回查来源，不要求普通读者连续硬读。每页先说明本页推进什么；正文释义仍有疑处时会标出释读状态；图式按实际图像插入，并提供逐图阅读提示。卷四所有图先看来脉、再看水线、再看收或泄；单图只说明它特有的判断边界。", ""]
    current_chapter = None
    current_page = None
    uncertainty_notice_emitted = False
    for row in rows:
        bid = row.get("block_id", "")
        if not bid.startswith("P"):
            continue
        pg = page_of(bid)
        chapter = next((x for x in CHAPTERS if x[0] <= pg <= x[1]), None)
        if chapter and chapter != current_chapter:
            current_chapter = chapter
            out += [f"## {chapter[2]}", "", f"**本章问题：** {chapter[4]}", "", f"**阅读抓手：** {chapter[3]}。", ""]
            if pg in GUIDES:
                title, guide = GUIDES[pg]
                out += [f"> 编者提示｜{title}：{guide}", ""]
        if pg != current_page:
            current_page = pg
            uncertainty_notice_emitted = False
            out += [f"### 原书物理页 {pg}", "", f"**本页新增判断：** {PAGE_THEMES[pg]}", ""]
        if row.get("block_type") == "figure":
            asset = ROOT / "50-edited" / "assets" / "figures" / f"{bid}.jpg"
            if not asset.is_file():
                out += [f"> 图式 {bid}：原图资产缺失，暂不猜补。", ""]
                continue
            title, guide = FIGURE_GUIDES[bid]
            out += [f"#### 图式：{title}", "", f"![{title}](assets/figures/{bid}.jpg)", ""]
            if bid in REFERENCE_ONLY_FIGURES:
                out += ["**使用边界：仅保留原图，不承担教学证明。**", "", guide, "", "本版不为此图绘制现代示意，不建立编号映射，也不从模糊轮廓补出方位、穴位或因果结论。相关正文只能由文字证据与其他可辨图式支持。", ""]
            else:
                out += [f"**读图顺序与本图边界：** {guide}", ""]
            out += [f"<!-- source:{bid} -->", ""]
        else:
            text = block_text(row)
            if text:
                if not uncertainty_notice_emitted and re.search(r"具体所指不详|疑似|无法确认|无法通顺|残缺|讹误|可能存在错漏|文意未完", text):
                    out += ["> 释读状态：原文或版面存在疑损；下文仅保守转述，不可据此恢复精确方位、数字或操作规则。", ""]
                    uncertainty_notice_emitted = True
                out += [text, ""]
                if bid in SPECIAL_NOTES:
                    out += [f"> 编者核查：{SPECIAL_NOTES[bid]}", ""]
                out += [f"<!-- source:{bid} -->", ""]
    out += ["# 附录一：本书术语表", "", "这不是通用风水词典，而是本书的阅读词典。每条先说明普通读者在本书中应怎样理解，再指出它在判断链中的作用、最常见混淆和跨章用例。", ""]
    for entry in aids["glossary"]["entries"]:
        first = entry["first_occurrence"]
        out += [
            f"## {entry['term']}", "",
            entry["plain_definition"], "",
            f"**在本书中的作用：** {entry['contextual_definition']}", "",
            f"**本书用例：** {entry['usage_example']}", "",
            f"**不要混淆：** {entry['common_confusions']}", "",
            f"**首次原文：** {first['block_id']}（物理页 {first['source_page']}）：“{first['quote']}”", "",
        ]
        if entry.get("other_occurrences"):
            refs = "；".join(f"{x['block_id']}（页{x['source_page']}）" for x in entry["other_occurrences"])
            out += [f"**继续查阅：** {refs}", ""]
        if entry.get("related_terms"):
            out += [f"**相关词：** {'、'.join(entry['related_terms'])}", ""]
    out += ["# 附录二：主题、图式与疑文索引", "", "## 主题索引", "", "- 由水察势与平原微地形：物理页 6—9，P000006-B005—P000009-B006。", "- 行龙、尚行与住结：物理页 31—33，P000031-B002—P000033-B008。", "- 入首、真伪脉与具体取点：物理页 41—67。", "- 护砂、劫砂、鬼砂与关峡：物理页 52—56、68—75。", "- 二十四山、三合、纳甲、十二长生：物理页 18—24、41—48。", "- 山为体、水为用与立向：物理页 76—84。", "", "## 图式索引", ""]
    for bid, (title, _) in FIGURE_GUIDES.items():
        out += [f"- {bid}（物理页 {page_of(bid)}）：{title}"]
    out += ["", "## 疑文索引", "", "以下物理页含至少一处疑损释读；查阅时以页内‘释读状态’为准，不用于恢复精确算法：", ""]
    uncertain_pages = []
    for row in rows:
        text = block_text(row)
        if row.get("block_id", "").startswith("P") and re.search(r"具体所指不详|疑似|无法确认|无法通顺|残缺|讹误|可能存在错漏|文意未完", text):
            uncertain_pages.append(page_of(row["block_id"]))
    out += ["、".join(str(x) for x in sorted(set(uncertain_pages))) + "。", ""]
    out += ["# 附录三：读完后你应能回答的六个问题", "", "1. 为什么本书在平原上特别重视水痕和微小高差？", "2. 水交为什么只能算停聚候选，而不能单独证明穴已成立？", "3. 护砂、劫砂、鬼砂的差别应从什么相对关系来判断？", "4. 二十四山、三合、纳甲和十二长生分别在做哪一类分类？", "5. 为什么本书把立向放在来龙、水口和砂水之后？", "6. 面对吉凶断语和残缺公式，怎样区分观察、传统解释与当前未知？", ""]
    return "\n".join(out).rstrip() + "\n"


